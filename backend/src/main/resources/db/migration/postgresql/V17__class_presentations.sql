-- Giao bản trình chiếu (đã xuất bản) cho lớp, tương tự class_lectures.
-- DB mới: bảng cha chưa có khi Flyway chạy, Hibernate (ddl-auto=update) sẽ tạo bảng này.
DO $$
BEGIN
    IF to_regclass('public.classes') IS NOT NULL AND to_regclass('public.presentations') IS NOT NULL THEN
        CREATE TABLE IF NOT EXISTS class_presentations (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            class_id INTEGER NOT NULL REFERENCES classes(class_id),
            presentation_id UUID NOT NULL REFERENCES presentations(presentation_id),
            assigned_at TIMESTAMP(6) NOT NULL,
            CONSTRAINT uk_class_presentation UNIQUE (class_id, presentation_id)
        );
        CREATE INDEX IF NOT EXISTS idx_class_presentations_presentation ON class_presentations(presentation_id);
    END IF;
END $$;
